const rotateRef = (g) => seq(g[0].length, (c) => seq(g.length, (k) => g[g.length - 1 - k][c]));
const islandsRef = (g) => { const R = g.length; const C = g[0].length; const seen = seq(R, () => new Array(C).fill(false)); let n = 0; const fill = (r, c) => { if (r < 0 || r >= R || c < 0 || c >= C || !g[r][c] || seen[r][c]) return; seen[r][c] = true; fill(r + 1, c); fill(r - 1, c); fill(r, c + 1); fill(r, c - 1); }; for (let r = 0; r < R; r++) for (let c = 0; c < C; c++) if (g[r][c] && !seen[r][c]) { n++; fill(r, c); } return n; };
const robLine = (a) => { let take = 0; let skip = 0; for (const x of a) [take, skip] = [skip + x, Math.max(skip, take)]; return Math.max(take, skip); };
const robCircleRef = (a) => (a.length === 0 ? 0 : a.length === 1 ? a[0] : Math.max(robLine(a.slice(0, -1)), robLine(a.slice(1))));
const subsetRef = (a, t) => { const w = new Array(t + 1).fill(0); w[0] = 1; for (const x of a) for (let s = t; s >= x; s--) w[s] += w[s - x]; return w[t]; };
const pathRef = (g) => { const R = g.length; const C = g[0].length; const memo = seq(R, () => new Array(C).fill(0)); const walk = (r, c) => { if (memo[r][c]) return memo[r][c]; let best = 1; for (const [dr, dc] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) { const nr = r + dr; const nc = c + dc; if (nr >= 0 && nr < R && nc >= 0 && nc < C && g[nr][nc] > g[r][c]) best = Math.max(best, 1 + walk(nr, nc)); } memo[r][c] = best; return best; }; let ans = 0; for (let r = 0; r < R; r++) for (let c = 0; c < C; c++) ans = Math.max(ans, walk(r, c)); return ans; };
const squareRef = (g) => { const R = g.length; const C = g[0].length; const s = seq(R, () => new Array(C).fill(0)); let best = 0; for (let r = 0; r < R; r++) for (let c = 0; c < C; c++) if (g[r][c]) { s[r][c] = r && c ? 1 + Math.min(s[r - 1][c], s[r][c - 1], s[r - 1][c - 1]) : 1; best = Math.max(best, s[r][c]); } return best * best; };
const windowMaxRef = (a, k) => seq(a.length - k + 1, (i) => Math.max(...a.slice(i, i + k)));
const catalanRef = (n) => { const c = [1]; for (let m = 1; m <= n; m++) { c[m] = 0; for (let l = 0; l < m; l++) c[m] += c[l] * c[m - 1 - l]; } return c[n]; };
const subseqRef = (x, y) => { const w = new Array(y.length + 1).fill(0); w[0] = 1; for (const v of x) for (let j = y.length; j >= 1; j--) if (v === y[j - 1]) w[j] += w[j - 1]; return w[y.length]; };

