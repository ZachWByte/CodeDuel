// Bug Hunt versions of the warm-ups in code-race-classic-9.js. Each buggy
// program is the shared solution with a few pieces of text swapped.

const bh = (id, topic, title, fn, description, swaps, bugExplanation, solution = SOL[fn]) => {
  const { buggy, lines } = breakCode(solution, swaps);
  return {
    id, mode: 'bug-hunt', difficulty: 'easy', topic, title, languages: ALL, functionName: fn,
    description: `${description} Find and fix the bug.`,
    buggy: { sicpy: buggy, python: buggy },
    bugLines: { sicpy: lines, python: lines },
    bugExplanation,
    solution: { sicpy: solution, python: solution },
    tests: TESTS[fn],
  };
};

