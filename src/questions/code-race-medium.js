// Plain-JS helpers that compute expected answers for the bigger tests.
const subsetsOf = (xs) => {
  if (xs.length === 0) return [[]];
  const rest = subsetsOf(xs.slice(1));
  return [...rest, ...rest.map((r) => [xs[0], ...r])];
};
const permsOf = (xs) => (xs.length === 0
  ? [[]]
  : xs.flatMap((x) => permsOf(xs.filter((y) => y !== x)).map((p) => [x, ...p])));
const pascal = (n) => {
  let row = [1];
  for (let i = 0; i < n; i++) row = [...row, 0].map((v, j) => v + (j > 0 ? row[j - 1] : 0));
  return row;
};
const matrix = (rows, cols, f) => A(Array.from({ length: rows }, (_, r) => A(Array.from({ length: cols }, (_, c) => f(r, c)))));
const ints = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
const enumL = (a, b) => R(`enum_llist(${a}, ${b})`, `list(range(${a}, ${b + 1}))`);
const fn = (src) => R(src);

