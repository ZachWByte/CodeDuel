const windowRef = (a, limit) => { let best = 0; for (let i = 0; i < a.length; i++) { let s = 0; for (let j = i; j < a.length; j++) { s += a[j]; if (s > limit) break; best = Math.max(best, j - i + 1); } } return best; };
const warmerRef = (t) => t.map((x, i) => { const j = t.findIndex((y, k) => k > i && y > x); return j === -1 ? 0 : j - i; });
const lpsRef = (a) => { const n = a.length; if (!n) return 0; const dp = seq(n, () => new Array(n).fill(0)); for (let i = n - 1; i >= 0; i--) { dp[i][i] = 1; for (let j = i + 1; j < n; j++) dp[i][j] = a[i] === a[j] ? dp[i + 1][j - 1] + 2 : Math.max(dp[i + 1][j], dp[i][j - 1]); } return dp[0][n - 1]; };
const minPathRef = (g) => { const r = g.length; const c = g[0].length; const d = seq(r, () => new Array(c).fill(0)); for (let i = 0; i < r; i++) for (let j = 0; j < c; j++) d[i][j] = g[i][j] + (i === 0 && j === 0 ? 0 : Math.min(i > 0 ? d[i - 1][j] : Infinity, j > 0 ? d[i][j - 1] : Infinity)); return d[r - 1][c - 1]; };
const partitionsRef = (n) => { const w = new Array(n + 1).fill(0); w[0] = 1; for (let p = 1; p <= n; p++) for (let t = p; t <= n; t++) w[t] += w[t - p]; return w[n]; };
const rectRef = (h) => { let best = 0; for (let i = 0; i < h.length; i++) { let m = Infinity; for (let j = i; j < h.length; j++) { m = Math.min(m, h[j]); best = Math.max(best, m * (j - i + 1)); } } return best; };
const inversionsRef = (a) => { let c = 0; for (let i = 0; i < a.length; i++) for (let j = i + 1; j < a.length; j++) if (a[i] > a[j]) c++; return c; };
const commonRunRef = (x, y) => { let best = 0; for (let i = 0; i < x.length; i++) for (let j = 0; j < y.length; j++) { let k = 0; while (i + k < x.length && j + k < y.length && x[i + k] === y[j + k]) k++; best = Math.max(best, k); } return best; };
const eggRef = (e, f) => { const m = seq(e + 1, () => new Array(f + 1).fill(0)); for (let k = 1; k <= f; k++) m[1][k] = k; for (let i = 2; i <= e; i++) for (let k = 1; k <= f; k++) { let best = k; for (let x = 1; x <= k; x++) best = Math.min(best, 1 + Math.max(m[i - 1][x - 1], m[i][k - x])); m[i][k] = best; } return m[e][f]; };
const maxProductRef = (a) => { let best = -Infinity; for (let i = 0; i < a.length; i++) { let p = 1; for (let j = i; j < a.length; j++) { p *= a[j]; best = Math.max(best, p); } } return best; };

